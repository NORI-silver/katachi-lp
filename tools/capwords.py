# 意味の違う決まった言い方（先に消す）
NOT_RX = re.compile(
    "|".join([
        r"ガラス繊維", r"グラスファイバー", r"ガラス(フィルム|基板|工事)", r"(安全|自動車用?)ガラス",
        r"包装(機械|機器|機)", r"(食品|製菓|製パン|製麺|菓子|化粧品|飲料)(?=(機械|機器|加工機|製造機|製造装置|工場|容器|ボトル|パッケージ|包装|ラベル))",
        r"半導体シリコン", r"シリコン(ウェ[ハー]|ウエハ|単結晶|半導体)", r"ゴム印",
        r"ソフトウェアパッケージ", r"パッケージ(ソフト|型)", r"(建築|土木|シールド)工法",
        r"(喫茶|茶碗|茶器|茶道具|茶色|茶道)", r"(フォーク)?リフト", r"電子部品(商社|の販売|販売|卸)", r"(印刷|包装)(機械|機器)",
        r"(焼結|焼却|焼肉)", r"(自動車|車両|車)の?(板金|鈑金)塗装", r"鈑金塗装", r"自動車整備", r"ガソリンスタンド", r"(圧力|高圧ガス)容器", r"(リネン|クリーニング)",
        # 「◯◯用」「◯◯向け」「◯◯付属金具」は、その品を作る会社ではない（「家具用金属部品」「化粧品用容器」「鞄・袋物付属金具」）
        r"(家具|鞄|かばん|カバン|バッグ|袋物|食品|化粧品|衣料|靴|菓子)(用|向け)", r"[^、。,]{0,15}付属(金具|品|部品)",
    ]))
KTK = re.compile(r"[ァ-ヶー]")
ASC = re.compile(r"[A-Za-z]")


def _cls(ch: str):
    return KTK if KTK.match(ch) else ASC if ASC.match(ch) else None


def _norm(s: str) -> str:
    return unicodedata.normalize("NFKC", s or "")


def _hits(text: str):
    """(開始, 終了, 言葉, 工程) を全部返す。カタカナの言葉は前後がカタカナの所では当てない"""
    out = []
    for kws, code in KEYWORD_CAPS:
        for k in kws:
            k = _norm(k)
            p = text.find(k)
            while p >= 0:
                e = p + len(k)
                a, b = (_cls(k[0]), _cls(k[-1])) if len(k) <= 3 else (None, None)
                if not (a and p > 0 and a.match(text[p - 1])) and not (b and e < len(text) and b.match(text[e])):
                    out.append((p, e, k, code))
                p = text.find(k, p + 1)
    return out


# 材料つきの「◯◯雑貨」は、その材料の製品として読む（「金属雑貨」は金属製品で、雑貨のOEMではない）
MAT_GOODS = re.compile(r"(金属|木製|木|陶器|陶|革|布|ガラス|プラスチック|樹脂)雑貨")


def infer_caps(text: str) -> list[str]:
    t = NOT_RX.sub("　", MAT_GOODS.sub(lambda m: m.group(1) + "製品", _norm(text)))
    hits = _hits(t)
    # 長い言葉が当たった所の中の短い言葉は使わない（同じ工程の言葉どうしは残す）
    keep = [h for h in hits if not any(o[0] <= h[0] and h[1] <= o[1] and (o[1] - o[0]) > (h[1] - h[0]) and o[3] != h[3] for o in hits)]
    caps = []
    for kws, code in KEYWORD_CAPS:
        if code not in caps and any(h[3] == code for h in keep):
            caps.append(code)
    return caps


